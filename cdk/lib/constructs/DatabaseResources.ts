import { Duration, RemovalPolicy } from "aws-cdk-lib";
import {
  InstanceClass,
  InstanceSize,
  InstanceType,
  Peer,
  Port,
  SecurityGroup,
  SubnetType,
  type IVpc,
} from "aws-cdk-lib/aws-ec2";
import * as iam from "aws-cdk-lib/aws-iam";
import {
  Credentials,
  DatabaseInstance,
  DatabaseInstanceEngine,
  DatabaseProxy,
  ParameterGroup,
  PostgresEngineVersion,
} from "aws-cdk-lib/aws-rds";
import * as secretsmanager from "aws-cdk-lib/aws-secretsmanager";
import { Construct } from "constructs";
import { APP_DB_ROLES, appDbRolePascal, type AppDbRole } from "../appDbRoles.js";
import { resolveLogRetention, type AppConfig } from "../config.js";

export interface DatabaseResourcesProps {
  readonly config: AppConfig;
  /** Concrete VPC the database and proxy live in (passed in by the stack). */
  readonly vpc: IVpc;
}

/**
 * Relational persistence layer: RDS PostgreSQL 16 (reference
 * grounding is full-text) fronted by an RDS Proxy with TLS required.
 *
 * Security / residency posture (REQ-SEC-PII-01, REQ-NFR-RESIDENCY-01, steering):
 *   - Instance + proxy live in the VPC's isolated subnets (no public access).
 *   - `storageEncrypted: true`, `deletionProtection: true`,
 *     `RemovalPolicy.RETAIN` on the stateful instance.
 *   - A custom parameter group sets `rds.force_ssl = 1` so all client
 *     connections must use TLS.
 *   - Admin credentials are generated into Secrets Manager (never inlined).
 *
 * Per the CDK steering the incoming props are saved as a private field and all
 * resources are created in protected methods, and the construct is passed the
 * concrete VPC rather than importing it.
 */
export class DatabaseResources extends Construct {
  public readonly instance: DatabaseInstance;
  public readonly proxy: DatabaseProxy;
  public readonly parameterGroup: ParameterGroup;
  public readonly securityGroup: SecurityGroup;
  public readonly proxySecurityGroup: SecurityGroup;
  /** Per-app-role Secrets Manager secrets (RDS Proxy JSON: username + password). */
  public readonly appUserSecrets: Record<AppDbRole, secretsmanager.ISecret>;

  private readonly props: DatabaseResourcesProps;

  constructor(scope: Construct, id: string, props: DatabaseResourcesProps) {
    super(scope, id);
    this.props = props;

    this.parameterGroup = this.createParameterGroup();
    this.securityGroup = this.createInstanceSecurityGroup();
    this.proxySecurityGroup = this.createProxySecurityGroup();
    this.instance = this.createInstance();
    this.appUserSecrets = this.createAppUserSecrets();
    this.proxy = this.createProxy();
  }

  /** The Secrets Manager secret holding generated admin credentials. */
  public get credentialsSecret() {
    // `secret` is always defined when credentials are generated by CDK.
    return this.instance.secret!;
  }

  protected createAppUserSecrets(): Record<AppDbRole, secretsmanager.ISecret> {
    const secrets = {} as Record<AppDbRole, secretsmanager.ISecret>;
    for (const role of APP_DB_ROLES) {
      secrets[role] = new secretsmanager.Secret(
        this,
        `AppUserSecret${appDbRolePascal(role)}`,
        {
          secretName: `${this.props.config.stackPrefix}/database/${role}`,
          description: `RDS Proxy credentials for Postgres role ${role}`,
          generateSecretString: {
            secretStringTemplate: JSON.stringify({
              username: role,
              port: 5432,
              dbname: "appdb",
              engine: "postgres",
            }),
            generateStringKey: "password",
            excludeCharacters: " %+~`#$&*()|[]{}:;<>?!'/@\"\\",
            passwordLength: 32,
          },
        },
      );
    }
    return secrets;
  }

  protected createParameterGroup(): ParameterGroup {
    return new ParameterGroup(this, "ParameterGroup", {
      engine: DatabaseInstanceEngine.postgres({
        version: PostgresEngineVersion.VER_16_13,
      }),
      description:
        "Enforce TLS for all PostgreSQL client connections (rds.force_ssl).",
      parameters: {
        "rds.force_ssl": "1",
      },
    });
  }

  protected createInstanceSecurityGroup(): SecurityGroup {
    return new SecurityGroup(this, "InstanceSecurityGroup", {
      vpc: this.props.vpc,
      description: "Ingress to the PostgreSQL instance from the RDS Proxy only.",
      allowAllOutbound: false,
    });
  }

  protected createProxySecurityGroup(): SecurityGroup {
    return new SecurityGroup(this, "ProxySecurityGroup", {
      vpc: this.props.vpc,
      description: "RDS Proxy security group.",
      allowAllOutbound: true,
    });
  }

  protected createInstance(): DatabaseInstance {
    // Control Tower CT.RDS.PR.2 requires Enhanced Monitoring on RDS instances.
    const monitoringRole = new iam.Role(this, "MonitoringRole", {
      assumedBy: new iam.ServicePrincipal("monitoring.rds.amazonaws.com"),
      managedPolicies: [
        iam.ManagedPolicy.fromAwsManagedPolicyName(
          "service-role/AmazonRDSEnhancedMonitoringRole",
        ),
      ],
    });

    return new DatabaseInstance(this, "Instance", {
      engine: DatabaseInstanceEngine.postgres({
        version: PostgresEngineVersion.VER_16_13,
      }),
      vpc: this.props.vpc,
      vpcSubnets: { subnetType: SubnetType.PRIVATE_ISOLATED },
      securityGroups: [this.securityGroup],
      instanceType: InstanceType.of(
        InstanceClass.BURSTABLE3,
        InstanceSize.MEDIUM,
      ),
      parameterGroup: this.parameterGroup,
      // Credentials are generated into Secrets Manager — never inlined.
      credentials: Credentials.fromGeneratedSecret("dbadmin", {
        secretName: `${this.props.config.stackPrefix}/database/credentials`,
      }),
      databaseName: "appdb",
      multiAz: false,
      allocatedStorage: 50,
      storageEncrypted: true,
      deletionProtection: true,
      backupRetention: Duration.days(7),
      removalPolicy: RemovalPolicy.RETAIN,
      monitoringInterval: Duration.seconds(60),
      monitoringRole,
      // Engine log export. Enhanced Monitoring above only covers
      // OS-level metrics; export the PostgreSQL engine logs (error / slow-query
      // / connection) and major-version `upgrade` logs to CloudWatch Logs for
      // troubleshooting and audit. `cloudwatchLogsRetention` bounds the
      // auto-created `/aws/rds/instance/{id}/postgresql` group on the project's
      // 90-day-prod / 30-day-else schedule instead of letting it accrue forever.
      cloudwatchLogsExports: ["postgresql", "upgrade"],
      cloudwatchLogsRetention: resolveLogRetention(this.props.config),
    });
  }

  protected createProxy(): DatabaseProxy {
    const proxy = this.instance.addProxy("Proxy", {
      vpc: this.props.vpc,
      secrets: [
        this.credentialsSecret,
        ...APP_DB_ROLES.map((role) => this.appUserSecrets[role]),
      ],
      securityGroups: [this.proxySecurityGroup],
      requireTLS: true,
      dbProxyName: `${this.props.config.stackPrefix}-db-proxy`,
    });

    // Allow the proxy to reach the database over the PostgreSQL port.
    this.securityGroup.addIngressRule(
      this.proxySecurityGroup,
      Port.tcp(5432),
      "Allow RDS Proxy to reach PostgreSQL",
    );

    // Allow in-VPC compute (the service Lambdas run in private subnets) to
    // reach the proxy over TLS PostgreSQL. Scoped to the VPC CIDR so no
    // cross-stack security-group reference (and thus no circular stack
    // dependency) is introduced between Database and Compute.
    this.proxySecurityGroup.addIngressRule(
      Peer.ipv4(this.props.vpc.vpcCidrBlock),
      Port.tcp(5432),
      "Allow in-VPC Lambdas to reach the RDS Proxy",
    );

    return proxy;
  }
}
