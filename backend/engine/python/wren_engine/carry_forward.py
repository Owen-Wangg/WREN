"""Carry-forward caching and invalidation (Task 9.10).

Reuses prior Feedback Items for spans that are unchanged in both text and
governing Document-Type configuration, avoiding redundant model invocations
(REQ-NFR-COST-01 / Requirement 49). Invalidates cached feedback when:

1. The text in the feedback item's anchored span has changed (text change).
2. The Document-Type config's ``updatedAt`` is newer than the feedback
   item's generation timestamp (config change — REQ-CONFIG-CONV-01
   criterion 3 / Requirement 27.3).

Persisted feedback is loaded on re-open without regeneration
(Requirement 49.4), and only changed/new spans are sent to the engine.

Key design decisions:
- Cache key = (document_id, draft_version, anchor_fingerprint, config_hash).
- Structural (non-anchored) items are keyed on (document_id, draft_version,
  config_hash) — they're invalidated on ANY text change or config change
  since they assess the whole document.
- Carry-forward is conservative: if in doubt, invalidate (regenerate).
- This module is pure logic (no DB I/O); persistence is handled by callers.

Design references:
  - design.md "Carry-forward & caching: reuses prior Feedback Items for
    spans unchanged in text *and* governing config; invalidates on text
    change or config change."
  - requirements.md Requirement 10.3 (REQ-DRAFT-DIFF-01 criterion 3),
    Requirement 27.3 (REQ-CONFIG-CONV-01 criterion 3),
    Requirement 49 (REQ-NFR-COST-01) criteria 49.1, 49.2, 49.4.
  - Property 9: Carry-forward caching.
"""
from __future__ import annotations

import hashlib
from dataclasses import dataclass, field
from datetime import datetime
from typing import Optional

from .anchor_service import ContentFingerprint, compute_fingerprint
from .output_guardrail import ValidatedFeedbackItem
from .structural_feedback import StructuralFeedbackItem

__all__ = [
    "CachedFeedbackItem",
    "CacheKey",
    "ConfigSnapshot",
    "CarryForwardDecision",
    "CarryForwardCache",
]


@dataclass(frozen=True, slots=True)
class ConfigSnapshot:
    """Snapshot of the Document-Type configuration at feedback generation time.

    Used to detect config changes that invalidate cached feedback
    (REQ-CONFIG-CONV-01 criterion 3 / Requirement 27.3).
    """

    config_hash: str
    updated_at: datetime

    @staticmethod
    def from_config(
        *,
        category_names: tuple[str, ...],
        tone: str,
        density: str,
        category_priority: tuple[str, ...] = (),
        type_instructions: str = "",
        updated_at: datetime,
    ) -> "ConfigSnapshot":
        """Create a snapshot by hashing the relevant config fields.

        The hash covers all fields that influence feedback generation.
        A change in any of these fields means prior feedback is stale.
        """
        hasher = hashlib.sha256()
        hasher.update("|".join(category_names).encode("utf-8"))
        hasher.update(tone.encode("utf-8"))
        hasher.update(density.encode("utf-8"))
        hasher.update("|".join(category_priority).encode("utf-8"))
        hasher.update(type_instructions.encode("utf-8"))
        return ConfigSnapshot(
            config_hash=hasher.hexdigest(),
            updated_at=updated_at,
        )


@dataclass(frozen=True, slots=True)
class CacheKey:
    """Cache key for a feedback item.

    For anchored (inline) items: keyed on anchor fingerprint + config hash.
    For structural items: keyed on full document content hash + config hash.
    """

    span_fingerprint: str  # ContentFingerprint hex or full-doc hash
    config_hash: str
    is_structural: bool = False


@dataclass(frozen=True, slots=True)
class CachedFeedbackItem:
    """A feedback item stored with its cache key and generation metadata.

    Carries enough information to decide carry-forward validity.
    """

    item: ValidatedFeedbackItem | StructuralFeedbackItem
    cache_key: CacheKey
    generated_at: datetime
    config_snapshot: ConfigSnapshot


@dataclass(frozen=True, slots=True)
class CarryForwardDecision:
    """Result of carry-forward evaluation for a set of cached items.

    ``carried_forward``: items whose span AND config are unchanged —
    reuse directly, no model call needed.
    ``invalidated``: items whose span or config changed — must be
    regenerated by the engine.
    ``new_spans``: spans (paragraph indices) with no prior feedback —
    need fresh generation.
    """

    carried_forward: tuple[CachedFeedbackItem, ...]
    invalidated: tuple[CachedFeedbackItem, ...]
    new_span_indices: tuple[int, ...]


class CarryForwardCache:
    """Determines which prior feedback items can be carried forward (Task 9.10).

    Pure logic — no persistence. Callers supply the prior cached items and
    the current draft/config state; this module returns the carry-forward
    decision. Persistence (loading/storing cached items) is the caller's
    responsibility.
    """

    def evaluate(
        self,
        *,
        prior_items: list[CachedFeedbackItem],
        current_span_fingerprints: dict[int, str],
        current_config: ConfigSnapshot,
        current_doc_hash: Optional[str] = None,
    ) -> CarryForwardDecision:
        """Evaluate which prior items can be carried forward.

        Parameters:
        - ``prior_items``: previously cached feedback items from the prior
          draft/generation cycle.
        - ``current_span_fingerprints``: mapping of paragraph index → content
          fingerprint for the current draft's spans. Used to check if an
          anchored item's text has changed.
        - ``current_config``: the current Document-Type config snapshot.
          If its hash differs from a cached item's config_snapshot, that
          item is invalidated (Requirement 27.3).
        - ``current_doc_hash``: hash of the full current document text.
          Used for structural items (which assess the whole document).
        """
        carried_forward: list[CachedFeedbackItem] = []
        invalidated: list[CachedFeedbackItem] = []
        covered_spans: set[int] = set()

        for cached in prior_items:
            if self._is_valid(cached, current_span_fingerprints, current_config, current_doc_hash):
                carried_forward.append(cached)
                # Track which spans are covered by carried-forward items
                if not cached.cache_key.is_structural and cached.item.anchor is not None:
                    anchor = cached.item.anchor
                    if isinstance(anchor, dict) and "paragraph" in anchor:
                        covered_spans.add(anchor["paragraph"])
            else:
                invalidated.append(cached)

        # Identify new spans (present in current but not covered by carry-forward)
        all_span_indices = set(current_span_fingerprints.keys())
        new_span_indices = sorted(all_span_indices - covered_spans)

        return CarryForwardDecision(
            carried_forward=tuple(carried_forward),
            invalidated=tuple(invalidated),
            new_span_indices=tuple(new_span_indices),
        )

    def _is_valid(
        self,
        cached: CachedFeedbackItem,
        current_span_fingerprints: dict[int, str],
        current_config: ConfigSnapshot,
        current_doc_hash: Optional[str],
    ) -> bool:
        """Check if a cached item is still valid (unchanged text + config).

        Invalidation conditions (any one → invalid):
        1. Config hash changed → the governing config was edited.
        2. For anchored items: the span's content fingerprint changed.
        3. For structural items: the full document hash changed (any text
           change means the structural assessment may be stale).
        """
        # Config change invalidates everything (Requirement 27.3)
        if cached.config_snapshot.config_hash != current_config.config_hash:
            return False

        if cached.cache_key.is_structural:
            # Structural items: invalidate on any document text change
            if current_doc_hash is None:
                return False  # Conservative: can't verify, invalidate
            return cached.cache_key.span_fingerprint == current_doc_hash
        else:
            # Anchored items: check if the specific span is unchanged
            return cached.cache_key.span_fingerprint in current_span_fingerprints.values()

    @staticmethod
    def make_cache_key_inline(
        span_fingerprint: str,
        config: ConfigSnapshot,
    ) -> CacheKey:
        """Create a cache key for an inline (anchored) item."""
        return CacheKey(
            span_fingerprint=span_fingerprint,
            config_hash=config.config_hash,
            is_structural=False,
        )

    @staticmethod
    def make_cache_key_structural(
        doc_hash: str,
        config: ConfigSnapshot,
    ) -> CacheKey:
        """Create a cache key for a structural (document-wide) item."""
        return CacheKey(
            span_fingerprint=doc_hash,
            config_hash=config.config_hash,
            is_structural=True,
        )

    @staticmethod
    def compute_document_hash(full_text: str) -> str:
        """Compute a stable hash of the full document text.

        Used for structural item cache keys. A change in any part of the
        document invalidates structural items (they assess the whole doc).
        """
        return hashlib.sha256(full_text.encode("utf-8")).hexdigest()
